def get_flight_budget(country_code):
    """Return (region_label, max_usd) for the given ISO country code, or None if unknown."""
    return _BUDGETS.get(country_code.upper()) if country_code else None


# Budget regions that count as "East Africa" for the review region scoring field
_EAST_AFRICA_BUDGET_REGIONS = {'East Africa', 'Horn of Africa', 'Indian Ocean Islands'}
_AFRICA_BUDGET_REGIONS = _EAST_AFRICA_BUDGET_REGIONS | {'Central Africa', 'Southern Africa', 'North Africa', 'West Africa'}


def get_review_region(country_code):
    """
    Map a country ISO code to a FinAidApplicationReview.REGION_* choice:
      'uganda'         → applicant is from Uganda
      'east_africa'    → East Africa / Horn of Africa / Indian Ocean Islands (excl. Uganda)
      'other_africa'   → rest of Africa
      'outside_africa' → outside Africa or unknown
    """
    if not country_code:
        return 'outside_africa'
    code = country_code.upper()
    if code == 'UG':
        return 'uganda'
    budget = _BUDGETS.get(code)
    if budget:
        if budget[0] in _EAST_AFRICA_BUDGET_REGIONS:
            return 'east_africa'
        if budget[0] in _AFRICA_BUDGET_REGIONS:
            return 'other_africa'
    return 'outside_africa'
